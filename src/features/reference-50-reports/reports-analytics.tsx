function downloadFile(filename: string, content: string, type = "text/csv;charset=utf-8") {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  URL.revokeObjectURL(url);
}

function makeReportCsv(rows: ReportRow[]) {
  const values: Array<Array<string | number>> = [
    ["Metric", "Value", "Change vs Apr 2025"],
    ...summaryMetrics.map((metric) => [metric.label, metric.value, `${metric.tone === "positive" ? "+" : "-"}${metric.change}`]),
    [],
    ["Report Name", "Category", "Generated On", "Generated By", "Format"],
    ...rows.map((row) => [row.name, row.category, row.generatedOn, row.generatedBy, row.format]),
  ];

  return `\uFEFF${values.map((row) => row.map((value) => `"${String(value).replaceAll('"', '""')}"`).join(",")).join("\n")}`;
}

