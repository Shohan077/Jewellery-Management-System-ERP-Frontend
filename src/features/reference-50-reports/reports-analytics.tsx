export function ReportsAnalytics197() {
  const [activeTab, setActiveTab] = useState<ReportTab>("Overview");
  const [range, setRange] = useState(rangeOptions[0]);
  const [interval, setInterval] = useState("Daily");
  const [exportMenuOpen, setExportMenuOpen] = useState(false);
  const [showAll, setShowAll] = useState(false);
  const [message, setMessage] = useState("");

  const visibleReports = useMemo(() => {
    const filtered = activeTab === "Overview" || activeTab === "Custom Reports"
      ? reportRows
      : reportRows.filter((row) => row.category === activeTab);
    return showAll ? filtered : filtered.slice(0, 5);
  }, [activeTab, showAll]);

  function exportCsv() {
    downloadFile("reports-analytics-may-2025.csv", makeReportCsv(visibleReports));
    setMessage(`${activeTab} report exported as CSV.`);
    setExportMenuOpen(false);
  }

  function downloadReport(row: ReportRow) {
    const safeName = row.name.toLowerCase().replaceAll(/[^a-z0-9]+/g, "-").replaceAll(/^-|-$/g, "");
    const details = `Report Name,${row.name}\nCategory,${row.category}\nGenerated On,${row.generatedOn}\nGenerated By,${row.generatedBy}\nFormat,${row.format}\n`;
    downloadFile(`${safeName}.csv`, `\uFEFF${details}`);
    setMessage(`${row.name} downloaded.`);
  }

  return (
    <div className={styles.page}>
      <PageHeader
        action={(
          <div className={styles.headerActions}>
            <label className={styles.rangeControl}>
              <CalendarDays aria-hidden="true" size={15} />
              <span className="sr-only">Reporting period</span>
              <select
                aria-label="Reporting period"
                onChange={(event) => {
                  setRange(event.target.value);
                  setMessage(`Reporting period changed to ${event.target.value}.`);
                }}
                value={range}
              >
                {rangeOptions.map((option) => <option key={option}>{option}</option>)}
              </select>
            </label>
            <div className={styles.exportControl}>
              <button className={styles.exportButton} onClick={exportCsv} type="button">
                <Download aria-hidden="true" size={15} />
                Export Report
              </button>
              <button
                aria-expanded={exportMenuOpen}
                aria-haspopup="menu"
                aria-label="Open export options"
                className={styles.exportToggle}
                onClick={() => setExportMenuOpen((open) => !open)}
                type="button"
              >
                <ChevronDown aria-hidden="true" size={15} />
              </button>
              {exportMenuOpen ? (
                <div className={styles.exportMenu} role="menu">
                  <button onClick={exportCsv} role="menuitem" type="button"><FileSpreadsheet aria-hidden="true" size={14} />Export CSV</button>
                  <button
                    onClick={() => {
                      setExportMenuOpen(false);
                      setMessage("Print preview opened. Choose Save as PDF to create a PDF report.");
                      window.setTimeout(() => window.print(), 0);
                    }}
                    role="menuitem"
                    type="button"
                  >
                    <Printer aria-hidden="true" size={14} />Print / Save PDF
                  </button>
                </div>
              ) : null}
            </div>
          </div>
        )}
        description="Analyze your business performance and key metrics"
        title="Reports & Analytics"
      />

      <section aria-label="Report highlights" className={styles.metricsGrid}>
        {summaryMetrics.map((metric) => <SummaryCard key={metric.label} metric={metric} />)}
      </section>

      <nav aria-label="Report categories" className={styles.tabs} role="tablist">
        {tabs.map((tab) => (
          <button
            aria-selected={activeTab === tab}
            className={activeTab === tab ? styles.activeTab : ""}
            key={tab}
            onClick={() => {
              setActiveTab(tab);
              setShowAll(false);
              setMessage(`${tab} analytics selected.`);
            }}
            role="tab"
            type="button"
          >
            {tab}
          </button>
        ))}
      </nav>

      <section aria-label="Analytics charts" className={styles.analyticsGrid}>
        <Card className={styles.chartCard}>
          <header className={styles.cardHeader}>
            <div>
              <h2>Sales Trend</h2>
              <span>Amount (₹)</span>
            </div>
            <select aria-label="Sales trend interval" onChange={(event) => setInterval(event.target.value)} value={interval}>
              <option>Daily</option>
              <option>Weekly</option>
              <option>Monthly</option>
            </select>
          </header>
          <SalesTrendChart interval={interval} />
          <div className={styles.chartLegend}><i />Sales (₹)</div>
        </Card>

        <Card className={styles.categoryCard}>
          <header className={styles.cardHeader}><h2>Sales by Category</h2></header>
          <div className={styles.categoryContent}>
            <div
              aria-label="Total sales ₹2,45,80,920, split by product category"
              className={styles.donut}
              role="img"
            >
              <div><strong>₹ 2,45,80,920</strong><span>Total Sales</span></div>
            </div>
            <ul className={styles.categoryLegend}>
              {categoryData.map((category) => (
                <li key={category.label}>
                  <i style={{ backgroundColor: category.color }} />
                  <span>{category.label}</span>
                  <strong>{category.value}%</strong>
                </li>
              ))}
            </ul>
          </div>
        </Card>
      </section>

      <Card className={styles.reportsCard}>
        <header className={styles.cardHeader}>
          <h2>Recent Reports</h2>
        </header>
        {visibleReports.length ? (
          <ReportTable onDownload={downloadReport} onPreview={(row) => setMessage(`${row.name} preview selected.`)} rows={visibleReports} />
        ) : (
          <div className={styles.emptyState}>No recent reports are available for {activeTab}. Generate a custom report to get started.</div>
        )}
        <footer className={styles.reportsFooter}>
          <button
            className={styles.viewAll}
            onClick={() => {
              setShowAll((current) => !current);
              setMessage(showAll ? "Showing the five most recent reports." : "Showing all recent reports.");
            }}
            type="button"
          >
            {showAll ? "Show Recent" : "View All Reports"}
          </button>
        </footer>
      </Card>

      <p aria-live="polite" className={message ? styles.toast : "sr-only"}>{message}</p>
    </div>
  );
}
